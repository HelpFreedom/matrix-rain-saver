# Latin letters whose shape is identical to a Cyrillic glyph.
ALIASES = {
    "A": "А", "B": "В", "C": "С", "E": "Е", "H": "Н", "K": "К", "M": "М",
    "O": "О", "P": "Р", "T": "Т", "X": "Х", "Y": "У",
}

# Atlas order: stable, appended after the 64 original matrix cells.
GLYPH_ORDER = (
    list("АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ")
    + list("0123456789")
    + list("DFGIJLNQRSUVWZ")
    + list(".,-:!?«»()\"…%+/")
    + list("$₽€")  # appended last so existing atlas indices stay stable
)


def char_to_glyph(ch: str) -> str | None:
    """Resolve a character to a glyph name present in GLYPHS (or None)."""
    ch = ch.upper()
    if ch in ("Ё",):
        pass
    ch = ALIASES.get(ch, ch)
    return ch if ch in GLYPHS else None
